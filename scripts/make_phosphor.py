"""Copy the Phosphor fonts used by EZP on Windows and generate the name table.

Source: the `phosphoricons_flutter` package EZPWinApp depends on (pub cache).
Usage: python3 scripts/make_phosphor.py [path/to/phosphoricons_flutter-x.y.z]
"""
import re
import shutil
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
package = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / '.pub-cache/hosted/pub.dev/phosphoricons_flutter-1.0.0'
weights = {'regular': 'Phosphor.ttf', 'bold': 'Phosphor-Bold.ttf', 'fill': 'Phosphor-Fill.ttf'}
pattern = re.compile(r'assets/\w+/([a-z0-9-]+)\.svg\)\n\s+static const IconData \w+ = IconData\(\n\s+0x([0-9a-f]+)')

tables = {}
for weight in weights:
    source = (package / f'lib/src/phosphor_icons_{weight}.dart').read_text()
    tables[weight] = {name: int(code, 16) for name, code in pattern.findall(source)}
names = tables['regular']
assert len(names) > 1000, 'Không đọc được bảng Phosphor'
assert all(table == names for table in tables.values()), 'Mã ký tự khác nhau giữa các nét'

out = root / 'assets/phosphor'
out.mkdir(exist_ok=True)
for file in weights.values():
    shutil.copyfile(package / 'lib/fonts' / file, out / file)
shutil.copyfile(package / 'LICENSE', out / 'LICENSE-phosphoricons_flutter')

rows = '\n'.join(f'    ("{name}", 0x{code:04x}),' for name, code in sorted(names.items()))
(root / 'src/phosphor_table.rs').write_text(
    '// Generated by scripts/make_phosphor.py from phosphoricons_flutter; do not edit.\n'
    '// Same codepoints in the Regular, Bold and Fill fonts.\n'
    f'pub const ICONS: &[(&str, u32)] = &[\n{rows}\n];\n'
)
print(f'{len(names)} biểu tượng')
