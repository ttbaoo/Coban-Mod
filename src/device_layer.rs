//! Decoder for the optional Coban-mod firmware live-layer GET extension.
//! Stock firmware echoes this request; that must never become a layer value.
use anyhow::{Result, ensure};

pub const VALUE_ID: u8 = 0x65;
pub fn request() -> [u8; 32] {
    let mut report = [0xa5; 32];
    report[..3].copy_from_slice(&[8, 0, VALUE_ID]);
    report
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DeviceLayer {
    /// Zero-based, as reported by the QMK action engine.
    pub active: u8,
    pub count: u8,
    pub layer_mask: u32,
    pub default_mask: u32,
    pub uptime_ms: u32,
    pub image_safe: bool,
}
impl DeviceLayer {
    pub fn from_reply(reply: &[u8; 32]) -> Result<Option<Self>> {
        if reply[0] == 0xff {
            return Ok(None);
        }
        ensure!(
            reply[..3] == [8, 0, VALUE_ID],
            "Sai header đọc lớp bàn phím"
        );
        if &reply[3..7] != b"CBLR" {
            return Ok(None); // Stock echo or a different vendor extension.
        }
        ensure!(reply[7] == 1, "Phiên bản đọc lớp firmware chưa hỗ trợ");
        ensure!(
            reply[8] & 1 != 0 && reply[8] & !3 == 0,
            "Firmware báo trạng thái lớp không hợp lệ"
        );
        let read_u32 = |offset| u32::from_be_bytes(reply[offset..offset + 4].try_into().unwrap());
        let state = Self {
            active: reply[9],
            count: reply[10],
            layer_mask: read_u32(11),
            default_mask: read_u32(15),
            uptime_ms: read_u32(19),
            image_safe: reply[8] & 2 != 0,
        };
        ensure!(
            (1..=32).contains(&state.count),
            "Số lớp firmware không hợp lệ"
        );
        ensure!(state.active < state.count, "Lớp firmware vượt giới hạn");
        let effective = state.layer_mask | state.default_mask;
        let highest = if effective == 0 {
            0
        } else {
            31 - effective.leading_zeros() as u8
        };
        ensure!(
            state.active == highest,
            "Chỉ số lớp không khớp trạng thái QMK"
        );
        ensure!(
            reply[23..].iter().all(|b| *b == 0),
            "Trường dự phòng đọc lớp không hợp lệ"
        );
        Ok(Some(state))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> [u8; 32] {
        // Generated by the actual C encoder, which is also built into the UF2.
        hex::decode(include_str!("../firmware/layer-read/tests/layer-v1.hex").trim())
            .unwrap()
            .try_into()
            .unwrap()
    }
    #[test]
    fn reads_the_c_firmware_fixture_and_rejects_stock_echo() {
        assert_eq!(
            DeviceLayer::from_reply(&fixture()).unwrap(),
            Some(DeviceLayer {
                active: 2,
                count: 4,
                layer_mask: 4,
                default_mask: 1,
                uptime_ms: 0x12345678,
                image_safe: true,
            })
        );
        assert_eq!(DeviceLayer::from_reply(&request()).unwrap(), None);
        let mut unknown = request();
        unknown[0] = 0xff;
        assert_eq!(DeviceLayer::from_reply(&unknown).unwrap(), None);
        let mut zero_echo = [0; 32];
        zero_echo[..3].copy_from_slice(&[8, 0, VALUE_ID]);
        assert_eq!(DeviceLayer::from_reply(&zero_echo).unwrap(), None);
        let mut old_firmware = fixture();
        old_firmware[8] = 1;
        assert!(
            !DeviceLayer::from_reply(&old_firmware)
                .unwrap()
                .unwrap()
                .image_safe
        );
    }
    #[test]
    fn rejects_wrong_version_flags_bounds_and_inconsistent_layer() {
        for (offset, value) in [
            (0, 7),
            (7, 2),
            (8, 0x81),
            (9, 4),
            (9, 1),
            (10, 0),
            (10, 33),
            (31, 1),
        ] {
            let mut reply = fixture();
            reply[offset] = value;
            assert!(DeviceLayer::from_reply(&reply).is_err(), "offset {offset}");
        }
    }
    #[test]
    fn supports_layer_zero_default_layers_and_layer_31() {
        for (mask, default, count, active) in [
            (0u32, 0u32, 4, 0),
            (0, 8, 4, 3),
            (6, 1, 4, 2),
            (1 << 31, 1, 32, 31),
        ] {
            let mut reply = fixture();
            reply[9] = active;
            reply[10] = count;
            reply[11..15].copy_from_slice(&mask.to_be_bytes());
            reply[15..19].copy_from_slice(&default.to_be_bytes());
            assert_eq!(
                DeviceLayer::from_reply(&reply).unwrap().unwrap().active,
                active
            );
        }
    }

    #[test]
    fn protocol_uses_only_the_marked_get_and_expected_header() {
        struct Reply;
        impl crate::transport::Transport for Reply {
            fn exchange(&mut self, data: &[u8], echo: usize) -> Result<[u8; 32]> {
                assert_eq!(data, request());
                assert_eq!(echo, 3);
                Ok(fixture())
            }
        }
        let mut protocol = crate::protocol::Protocol::new(Reply);
        assert_eq!(protocol.read_active_layer().unwrap().unwrap().active, 2);
    }
}
